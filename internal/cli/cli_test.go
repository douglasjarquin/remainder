func TestExecuteBuildsFreshCommandInstances(t *testing.T) {
	var firstOut, firstErr bytes.Buffer
	if code := Execute(context.Background(), []string{"--help"}, &firstOut, &firstErr, "v0.1.0"); code != 0 {
		t.Fatalf("help exit code = %d, want 0", code)
	}

	var secondOut, secondErr bytes.Buffer
	code := Execute(context.Background(), nil, &secondOut, &secondErr, "v0.1.0")
	if code != 1 {
		t.Fatalf("unavailable exit code = %d, want 1", code)
	}
	if secondOut.Len() != 0 {
		t.Fatalf("second stdout = %q, want empty", secondOut.String())
	}
}

