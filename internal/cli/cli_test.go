package cli

import (
	"bytes"
	"context"
	"testing"
)

type cancelWriter struct {
	buffer bytes.Buffer
	cancel context.CancelFunc
}

func (w *cancelWriter) Write(data []byte) (int, error) {
	n, err := w.buffer.Write(data)
	w.cancel()
	return n, err
}

func TestExecuteHelpAndVersionUseStdout(t *testing.T) {
	tests := []struct {
		name string
		args []string
		want []string
	}{
		{name: "help", args: []string{"--help"}, want: []string{"Usage:", "remainder [flags]"}},
		{name: "version", args: []string{"--version"}, want: []string{"remainder v0.1.0 (github.com/douglasjarquin/remainder)"}},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			var stdout, stderr bytes.Buffer
			code := Execute(context.Background(), tt.args, &stdout, &stderr, "v0.1.0")
			if code != 0 {
				t.Fatalf("Execute() exit code = %d, want 0", code)
			}
			if stdout.String() == "" {
				t.Fatal("stdout is empty")
			}
			for _, want := range tt.want {
				if !bytes.Contains(stdout.Bytes(), []byte(want)) {
					t.Fatalf("stdout = %q, want substring %q", stdout.String(), want)
				}
			}
			if tt.name == "help" && bytes.Contains(stdout.Bytes(), []byte("completion")) {
				t.Fatalf("stdout = %q, want autogenerated completion disabled", stdout.String())
			}
			if stderr.Len() != 0 {
				t.Fatalf("stderr = %q, want empty", stderr.String())
			}
		})
	}
}

func TestExecuteRejectsUnknownFlag(t *testing.T) {
	var stdout, stderr bytes.Buffer
	code := Execute(context.Background(), []string{"--unknown"}, &stdout, &stderr, "v0.1.0")
	if code == 0 {
		t.Fatal("Execute() exit code = 0, want failure")
	}
	if stderr.Len() == 0 {
		t.Fatal("stderr is empty, want an actionable error")
	}
	if bytes.Contains(stderr.Bytes(), []byte("Usage:")) {
		t.Fatalf("stderr = %q, want no automatic usage", stderr.String())
	}
}

